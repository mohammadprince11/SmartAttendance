// تعطيل تأثيرات «التمرير-فوق» أثناء السكرول.
//
// **المشكلة المرصودة**: بالنظام قاعدة عامّة ترفع كل عنصرٍ تفاعليّ عند المرور فوقه
// (`transform: translateY(-1px)` + لمعان)، وعشرون ملف CSS فيها النمط نفسه
// (`translateY(-2px)` بالبطاقات ولوحات المفاتيح وبطاقات الإعدادات…).
//
// وحين تمرّر الصفحة يبقى المؤشّر **ثابتاً مكانه**، فينزلق المحتوى تحته وكل عنصر
// يمرّ تحت المؤشّر يقفز ويلمع ثم يهبط. عشرات العناصر تفعلها تباعاً، فتبدو الحقول
// وكأنها «تتحرّك معك ثم تفلت».
//
// **التشخيص مُثبَت بالقياس**: سُجِّل الفرق بين ودجت التاريخ وحقلٍ نصّيّ كل إطار
// أثناء تمريرٍ حقيقي بالعجلة عبر مواضع 200⟵700⟵300، فكان **‎−291.1px ثابتاً بصفر
// تباين** — أي لا تخلّف ولا انفصال بالتمرير إطلاقاً. الحركة كلّها من الـhover.
//
// الحلّ: علَمٌ على <html> أثناء التمرير، وقاعدة CSS تُسكِت التحويلات والانتقالات
// ما دام موجوداً. فتبقى تأثيرات الـhover كاملة حين تحرّك الماوس فعلاً، وتغيب
// تماماً حين تمرّر.
(function () {
    'use strict';

    var FLAG = 'zy-scrolling';
    // مهلة الإطفاء: أقصر منها يُبقي الوميض بين دفعات العجلة، وأطول يجعل أول
    // تمريرة فوق عنصرٍ بعد التوقّف تبدو ميّتة.
    var IDLE_MS = 140;

    var root = document.documentElement;
    var timer = null;

    function onScroll() {
        if (timer === null) {
            root.classList.add(FLAG);
        } else {
            clearTimeout(timer);
        }

        timer = setTimeout(function () {
            timer = null;
            root.classList.remove(FLAG);
        }, IDLE_MS);
    }

    // `capture` لأن حاوية التمرير عندنا ليست النافذة بل <main class="nexora-content">
    // (القوقعة تخطيطٌ ثابت والمحتوى يمرّ داخله)، وأحداث scroll لا تفقّع.
    // و`passive` كي لا نؤخّر التمرير نفسه.
    document.addEventListener('scroll', onScroll, { capture: true, passive: true });
})();
